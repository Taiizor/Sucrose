//! libmpv engine for video wallpapers.
//!
//! libmpv is loaded at runtime with `libloading` through the generated bindings in [`sys`] and is never linked
//! (D-013, D-017). Only renderer processes call into it; the service just asks [`loader::locate`] whether it exists.

// Engine/FFI crate: allowed to opt out of the workspace `unsafe_code` lint (D-011).
#![allow(unsafe_code)]

pub mod config;
pub mod loader;
pub mod player;
// The clock follower moved to `sucrose-engine` in Phase 4 so every time-based engine shares it (research Pattern 5);
// this re-export keeps the `sucrose_engine_mpv::sync` path for its callers.
pub use sucrose_engine::sync;

/// Dynamic-loading bindings for the pinned `client.h`, generated by `cargo xtask bindgen-mpv`.
#[allow(non_camel_case_types, non_upper_case_globals, non_snake_case, dead_code, clippy::all)]
pub mod sys;
