// Every user-visible string comes from the locale files (D-20): legacy.en.yml is generated by `cargo xtask localize`,
// sucrose.en.yml holds the keys new in Phase 3. Both load as locale "en".
rust_i18n::i18n!("locales", fallback = "en");

/// What the command line asks for.
#[derive(Debug, PartialEq, Eq)]
struct Args {
    /// The page to open on.
    page: PortalPage,
    /// Open the window without taking focus.
    no_focus: bool,
}

/// Reads the arguments (without the program name). Only `--no-focus`, `GeneralSetting` and `SystemSetting` are
/// accepted, each at most once; `SystemSetting` opens General too until the settings pages exist (UI-03).
fn parse_args(args: &[String]) -> Result<Args, String> {
    let mut page = None;
    let mut no_focus = false;
    for arg in args {
        match arg.as_str() {
            "--no-focus" if !no_focus => no_focus = true,
            "GeneralSetting" | "SystemSetting" if page.is_none() => page = Some(PortalPage::General),
            "--no-focus" | "GeneralSetting" | "SystemSetting" => {
                return Err(format!("{arg} is given more than once"));
            }
            _ => {
                return Err(format!(
                    "unknown argument {arg:?}; use --no-focus, GeneralSetting or SystemSetting"
                ));
            }
        }
    }
    Ok(Args {
        page: page.unwrap_or(PortalPage::Library),
        no_focus,
    })
}

impl Args {
    /// The page named in the PortalHello: only a page the user asked for, so a plain launch leaves the page of an
    /// open Portal alone.
    fn hello_page(&self) -> Option<PortalPage> {
        (self.page != PortalPage::Library).then_some(self.page)
    }
}

/// The exit code for a command line that cannot be understood (the same as the service's).
const EXIT_USAGE: u8 = 64;

/// The settings of the Welcome among the events that were ready before the window opened.
fn early_settings(early: &[ipc::LinkEvent]) -> Option<&PortalSettings> {
    early.iter().find_map(|event| match event {
        ipc::LinkEvent::Event(PortalEvent::Welcome { settings, .. }) => Some(settings),
        _ => None,
    })
}

/// The window title, localized.
pub(crate) fn window_title() -> String {
    rust_i18n::t!("Portal.MainWindow.Title").into_owned()
}

/// The version as the legacy app shows it (four components), without the "v".
pub(crate) fn version_text() -> String {
    sucrose_core::version::app_version().to_string()
}

fn main() -> anyhow::Result<ExitCode> {
    let _log = sucrose_log::init("Portal")?;
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let args = match parse_args(&arguments) {
        Ok(args) => args,
        Err(message) => {
            // The release build has no console, so the log is the only place the reason can be read.
            tracing::error!(%message, "the command line is not understood, nothing was started");
            return Ok(ExitCode::from(EXIT_USAGE));
        }
    };
    let no_focus = args.no_focus;
    let page = args.page;

    // Read once: whether this OS can show a window backdrop (D-22).
    let window_backdrop = sucrose_platform::current().capabilities().window_backdrop;

    // Say hello before any window exists: a second Portal ends on AlreadyOpen without a window flashing.
    let (link, events) = ipc::ServiceLink::start(args.hello_page());
    let early = ipc::first_events(&events, ipc::FIRST_EVENT_WAIT);
    if let Some(existing_pid) = early.iter().find_map(|event| match event {
        ipc::LinkEvent::Event(PortalEvent::AlreadyOpen { existing_pid }) => Some(*existing_pid),
        _ => None,
    }) {
        tracing::info!(existing_pid, "already open");
        return Ok(ExitCode::SUCCESS);
    }

    gpui_kit::application()
        .with_assets(assets::PortalAssets)
        .run(move |cx| {
            gpui_kit::init(cx);
            theme::install(cx);
            // The stored mode when the handshake finished before the window opened, so the first frame is not flashed
            // in the wrong theme; the app applies it again once it owns a window.
            theme::apply_initial(
                early_settings(&early).map_or(ThemeMode::System, |settings| settings.theme_mode),
                cx,
            );
            toast::configure(cx);
            cx.on_window_closed(|cx, _| {
                if cx.windows().is_empty() {
                    cx.quit();
                }
            })
            .detach();

            let backdrop = early_settings(&early).map_or(Backdrop::None, |settings| settings.backdrop);
            let bounds = Bounds::centered(None, size(px(900.), px(600.)), cx);
            let options = WindowOptions {
                window_bounds: Some(WindowBounds::Windowed(bounds)),
                window_min_size: Some(size(px(900.), px(600.))),
                focus: !no_focus,
                window_background: theme::appearance(backdrop, window_backdrop),
                titlebar: Some(TitlebarOptions {
                    title: Some(window_title().into()),
                    ..TitleBar::title_bar_options()
                }),
                ..TitleBar::window_options()
            };

            let opened = gpui_kit::open_window(options, cx, move |window, cx| {
                cx.new(|cx| app::PortalApp::new(page, link, window_backdrop, early, events, window, cx))
            });
            if let Err(error) = opened {
                tracing::error!(%error, "cannot open the Portal window");
                cx.quit();
                return;
            }
            if !no_focus {
                cx.activate(true);
            }
        });

    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    // Not `use super::*`: the crate root glob-imports GPUI, whose `test` macro would shadow the built-in attribute.
    use super::{Args, parse_args};
    use sucrose_ipc::portal::PortalPage;

    fn args(list: &[&str]) -> Vec<String> {
        list.iter().map(|arg| (*arg).to_owned()).collect()
    }

    #[test]
    fn no_argument_opens_the_library_and_takes_focus() {
        assert_eq!(
            parse_args(&args(&[])),
            Ok(Args {
                page: PortalPage::Library,
                no_focus: false
            })
        );
    }

    #[test]
    fn general_and_system_setting_both_open_general() {
        for page in ["GeneralSetting", "SystemSetting"] {
            assert_eq!(
                parse_args(&args(&[page])),
                Ok(Args {
                    page: PortalPage::General,
                    no_focus: false
                }),
                "{page}"
            );
        }
    }

    #[test]
    fn no_focus_keeps_both_flags_in_either_order() {
        let expected = Ok(Args {
            page: PortalPage::General,
            no_focus: true,
        });
        assert_eq!(parse_args(&args(&["--no-focus", "GeneralSetting"])), expected);
        assert_eq!(parse_args(&args(&["GeneralSetting", "--no-focus"])), expected);
        assert_eq!(
            parse_args(&args(&["--no-focus"])),
            Ok(Args {
                page: PortalPage::Library,
                no_focus: true
            })
        );
    }

    #[test]
    fn anything_else_is_refused() {
        for bad in [
            &["PersonalSetting"][..],
            &["x"],
            &["GeneralSetting", "GeneralSetting"],
            &["GeneralSetting", "SystemSetting"],
            &["--no-focus", "--no-focus"],
            &["--no-focus", "GeneralSetting", "x"],
            &["--nofocus"],
            &["generalsetting"],
            &[""],
        ] {
            assert!(parse_args(&args(bad)).is_err(), "{bad:?}");
        }
    }
    #[test]
    fn legacy_keys_resolve_to_their_text() {
        // Flat dotted keys of the generated file resolve like nested ones (RESEARCH assumption A7).
        let quote = rust_i18n::t!("Portal.Quoting0", locale = "en");
        assert_ne!(quote, "Portal.Quoting0");
        assert_eq!(quote, "Love conquers all");
        assert_eq!(
            rust_i18n::t!("Portal.MainWindow.Title", locale = "en"),
            "Sucrose Wallpaper Engine"
        );
    }
}
